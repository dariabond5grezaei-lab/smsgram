                onClick = onAction,
                shape = RoundedCornerShape(20.dp),
                colors = ButtonDefaults.buttonColors(
                    containerColor = MaterialTheme.colorScheme.primary
                )
            ) {
                Text(
                    text = actionLabel,
                    style = MaterialTheme.typography.labelLarge.copy(fontWeight = FontWeight.Bold)
                )
            }
        }
    }
}

/**
 * Standard Unified Navigation Bar for SMSGram
 */
@Composable
fun SmsGramBottomBar(
    currentTab: BottomTab,
    onTabSelected: (BottomTab) -> Unit,
    modifier: Modifier = Modifier,
    unreadChatsCount: Int = 0
) {
    NavigationBar(
        modifier = modifier,
        containerColor = MaterialTheme.colorScheme.surface,
        tonalElevation = 6.dp
    ) {
        val strings = appStrings()
        val isFa = (com.example.ui.locale.LocalAppLanguage.current == com.example.data.model.AppLanguage.PERSIAN)

        val items = listOf(
            BottomTab.CHATS to Triple(
                if (isFa) "پیام‌ها" else strings.allChats,
                Icons.Filled.Message,
                Icons.Outlined.Message
            ),
            BottomTab.FOLDERS to Triple(
                strings.folders,
                Icons.Filled.Folder,
                Icons.Outlined.Folder
            ),
            BottomTab.NOTES to Triple(
                if (isFa) "یادداشت‌ها" else "Notes",
                Icons.Filled.NoteAlt,
                Icons.Outlined.NoteAlt
            ),
            BottomTab.SETTINGS to Triple(
                strings.settings,
                Icons.Filled.Settings,
                Icons.Outlined.Settings
            )
        )

        items.forEach { (tab, details) ->
            val isSelected = currentTab == tab
            NavigationBarItem(
                selected = isSelected,
                onClick = { onTabSelected(tab) },
                icon = {
                    Icon(
                        imageVector = if (isSelected) details.second else details.third,
                        contentDescription = details.first,
                        modifier = Modifier.size(22.dp)
                    )
                },
                label = {
                    Text(
                        text = details.first,
                        style = MaterialTheme.typography.labelSmall.copy(
                            fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal,
                            fontSize = 11.sp
                        ),
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis
                    )
                },
                colors = NavigationBarItemDefaults.colors(
                    selectedIconColor = MaterialTheme.colorScheme.primary,
                    selectedTextColor = MaterialTheme.colorScheme.primary,
                    indicatorColor = MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.6f),
                    unselectedIconColor = MaterialTheme.colorScheme.onSurfaceVariant,
                    unselectedTextColor = MaterialTheme.colorScheme.onSurfaceVariant
                )
            )
        }
    }
}

enum class BottomTab {
    CHATS,
    FOLDERS,
    NOTES,
    SETTINGS
}
